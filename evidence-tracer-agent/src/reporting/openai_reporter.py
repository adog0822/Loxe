    def __init__(self) -> None:
        """Initialize the reporter, checking for demo mode."""
        self.demo_mode = os.getenv("DEMO_MODE", "false").lower() in ("true", "1", "yes")
        self.timestamp = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
        self.report_date = datetime.utcnow().strftime("%Y-%m-%d")

        if self.demo_mode:
            print("[DEMO] OpenAI Reporter initialized in DEMO MODE")
            print("[DEMO] Skipping OpenAI API credential validation")
            self.client = None
        else:
            api_key = os.getenv("OPENAI_API_KEY")
            if not api_key:
                raise ValueError(
                    "OPENAI_API_KEY environment variable is required. "
                    "Set DEMO_MODE=true to run without credentials."
                )
            try:
                from openai import OpenAI
                self.client = OpenAI(api_key=api_key)
            except ImportError:
                raise ImportError(
                    "openai package is required. Install with: pip install openai"
                )

    def generate_report(self, evidence: dict[str, Any] | None = None) -> str:
        """Generate a SOC 2 compliance report.

        Args:
            evidence: Collected evidence data. If None, uses demo data in demo mode.

        Returns:
            The generated report as a string.
        """
        if self.demo_mode:
            return self._generate_demo_report()

        if not evidence:
            raise ValueError("Evidence data is required in production mode.")

        return self._generate_openai_report(evidence)

    def _generate_openai_report(self, evidence: dict[str, Any]) -> str:
        """Generate report using OpenAI API.

        Args:
            evidence: Collected evidence data.

        Returns:
            The generated report from OpenAI.
        """
        prompt = self._build_prompt(evidence)
        response = self.client.chat.completions.create(
            model="gpt-4",
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You are a SOC 2 compliance expert. Generate a detailed "
                        "compliance report based on the provided evidence."
                    ),
                },
                {"role": "user", "content": prompt},
            ],
            temperature=0.3,
            max_tokens=4000,
        )
        return response.choices[0].message.content

    def _build_prompt(self, evidence: dict[str, Any]) -> str:
        """Build the prompt for OpenAI from evidence data.

        Args:
            evidence: Collected evidence data.

        Returns:
            Formatted prompt string.
        """
        return (
            f"Generate a SOC 2 Type II compliance report based on the following "
            f"evidence collected on {self.report_date}:\n\n"
            f"{json.dumps(evidence, indent=2, default=str)}"
        )

