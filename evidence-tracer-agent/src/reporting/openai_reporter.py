    def save_report(self, report: str, output_dir: str = "data") -> str:
        """Save the generated report to a file.

        Args:
            report: The report content to save.
            output_dir: Directory to save the report in.

        Returns:
            The path to the saved report file.
        """
        os.makedirs(output_dir, exist_ok=True)
        filename = f"soc2_compliance_report_{self.report_date}.txt"
        filepath = os.path.join(output_dir, filename)

        with open(filepath, "w") as f:
            f.write(report)

        print(f"Report saved to: {filepath}")
        return filepath

    def save_report_json(self, output_dir: str = "data") -> str:
        """Save a JSON summary of the report metadata.

        Args:
            output_dir: Directory to save the JSON in.

        Returns:
            The path to the saved JSON file.
        """
        os.makedirs(output_dir, exist_ok=True)
        filename = f"soc2_report_metadata_{self.report_date}.json"
        filepath = os.path.join(output_dir, filename)

        metadata = {
            "report_date": self.report_date,
            "generated_at": self.timestamp,
            "demo_mode": self.demo_mode,
            "overall_score": 78 if self.demo_mode else None,
            "controls_assessed": 8,
            "controls_compliant": 5,
            "controls_needs_remediation": 2,
            "controls_critical": 1,
            "findings": {
                "critical": 1,
                "high": 2,
                "medium": 1,
                "low": 1,
                "total": 5,
            },
            "risk_posture": "MODERATE",
            "risk_trend": "IMPROVING",
        }

        with open(filepath, "w") as f:
            json.dump(metadata, f, indent=2)

        print(f"Report metadata saved to: {filepath}")
        return filepath
